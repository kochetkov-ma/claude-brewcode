/**
 * The `## Agents` header separator, in the three spellings the parser must tell apart: the compact
 * one the shipped template writes, the space-padded one a markdown formatter produces, and none.
 */
const SEPARATORS = {
  compact: '|-------|--------|---------|--------|---------|------|---------|',
  padded: '| ------- | -------- | --------- | -------- | --------- | ------ | --------- |',
  malformedSlash: '|---/|--------|---------|--------|---------|------|---------|',
  none: null,
};

/**
 * A project root with one team. `rows` are `## Agents` Agent-column values, in table order;
 * `agentFiles` are the names actually written to .codex/agents/.
 */
const NATIVE_TEAM_TEMPLATE = "# Team: {TEAM_NAME}\n|Field|Value|\n|---|---|\n|Created|{DATE}|\n|Version|{PLUGIN_VERSION}|\n|Content version|{CONTENT_VERSION}|\n|Generated by|brewcode:teams-setup|\n|Last update|{LAST_UPDATED}|\n|Agents|{N}|\n|Agent defaults|active;{LAST_UPDATED};domain;{PLUGIN_VERSION}|\n|Intent guard|{INTENT_GUARD_POLICY}|\n|Project|{CWD}|\n\n## Shared Agent Contract\nLoad this before task acceptance. Gate Domain/Duplicate/Best: Mismatch/duplicate/better -> refuse+owner/link+return; accept -> trace took, execute only owned surfaces; exclusions win.\n{INTENT_GUARD_SHARED_CONTRACT}\nTrace via versionless project-local `.codex/teams/{TEAM_NAME}/trace-ops.sh`; T/trace-ops.sh; optional Bash once; `!=` retry/plugin root/env. Missing/fail -> skip; update/move/uninstall safe.\n`bash \".codex/teams/{TEAM_NAME}/trace-ops.sh\" add \".codex/teams/{TEAM_NAME}\" \"$SID\" \"{AGENT_NAME}\" \"<kind>\" \"<state>\" \"<text>\"`\nTrack took/refused/completed/failed; took -> 1 terminal. `$SID`: 8 chars; if unset choose any 8-char marker. Marker chars `[A-Za-z0-9._-]`. Issue low/medium/high/critical; <=3 insight pattern/architecture/performance/security/convention/debt.\nReturn with or without agent-return: verdict/path/check, `path:line`, <=30 lines; !=bodies/output/log/preamble. Return changed path/check only. Bulk -> `{REPORT_ROOT}/YYYYMMDD-HHMMSS_{AGENT_NAME}/`; !=content. Approx chars/4: >1000 compress; >2500 file+path+verdict+<=3 lines.\nActual scale; !=imagined load/speculative (10-user !=lock-contention). Class/module/test -> nearest .codex/convention/ etalon; additive to rules/conventions/docs, !=replace.\n\n## Agents\n|Agent|Domain|Mission|Status|Updated|Kind|Version|\n|---|---|---|---|---|---|---|\n{INTENT_GUARD_ROW}";
function nativeTeam(root, rows, separator = 'compact') {
  const intent = rows.includes('intent-guard');
  const domainRows = rows.filter((name) => name !== 'intent-guard');
  const intentRow = intent ? '|intent-guard|--|Anti-drift check: what was ASKED vs what was DELIVERED|active|2026-08-27|review-only|6.1.4|' : '';
  const roster = [intentRow, ...domainRows.map((name) => `|${name}|api|fixture mission|active|2026-08-27|domain|6.1.4|`)].filter(Boolean).join('\n');
  const rendered = `${NATIVE_TEAM_TEMPLATE
    .replaceAll('{TEAM_NAME}', 't1')
    .replaceAll('{DATE}', '2026-08-27')
    .replaceAll('{LAST_UPDATED}', '2026-08-27')
    .replaceAll('{PLUGIN_VERSION}', '6.1.4')
    .replaceAll('{CONTENT_VERSION}', '6.1.0')
    .replaceAll('{N}', String(domainRows.length))
    .replaceAll('{CWD}', root)
    .replaceAll('{REPORT_ROOT}', '.codex/reports')
    .replaceAll('{INTENT_GUARD_POLICY}', intent ? 'required' : 'legacy-absent')
    .replaceAll('{INTENT_GUARD_SHARED_CONTRACT}', intent ? '`intent-guard` is review-only, keeps its own output contract, and never implements.' : '')
    .replaceAll('{INTENT_GUARD_ROW}', roster)}\n`;
  const separators = { compact: '|---|---|---|---|---|---|---|', padded: '| --- | --- | --- | --- | --- | --- | --- |', none: '' };
  return rendered.replace('|---|---|---|---|---|---|---|', separators[separator]);
}

function makeProject(label, rows, agentFiles, separator = 'compact') {
  const root = join(BASE, label, 'proj');
  const teamDir = join(root, '.codex', 'teams', 't1');
  mkdirSync(join(root, '.codex', 'agents'), { recursive: true });
  mkdirSync(teamDir, { recursive: true });
  const policy = rows.includes('intent-guard') ? 'required' : 'legacy-absent';
  const domainRows = rows.filter((name) => name !== 'intent-guard')
    .map((name) => `|${name}|api|fixture mission|active|2026-08-16|domain|6.1.4|`);
  const guardRow = policy === 'required'
    ? '|intent-guard|--|Anti-drift check: what was ASKED vs what was DELIVERED|active|2026-08-16|review-only|6.1.4|'
    : '';
  const framework = readFileSync(FRAMEWORK, 'utf8');
  const headingAt = framework.indexOf('## team.md');
  const fenceAt = framework.indexOf('```markdown\n', headingAt) + '```markdown\n'.length;
  const fenceEnd = framework.indexOf('\n```', fenceAt);
  const canonicalSeparator = '|---|---|---|---|---|---|---|';
  const selectedSeparator = SEPARATORS[separator] ?? '';
  const team = framework.slice(fenceAt, fenceEnd)
    .replaceAll('{TEAM_NAME}', 't1')
    .replaceAll('{DATE}', '2026-08-16')
    .replaceAll('{LAST_UPDATED}', '2026-08-16')
    .replaceAll('{PLUGIN_VERSION}', '6.1.4')
    .replaceAll('{CONTENT_VERSION}', '6.1.0')
    .replaceAll('{N}', String(domainRows.length))
    .replaceAll('{CWD}', root)
    .replaceAll('{REPORT_ROOT}', '.codex/reports')
    .replaceAll('{INTENT_GUARD_POLICY}', policy)
    .replaceAll('{INTENT_GUARD_SHARED_CONTRACT}', policy === 'required'
      ? '`intent-guard` is review-only, keeps its own output contract, and never implements.' : '')
    .replaceAll('{INTENT_GUARD_ROW}', [guardRow, ...domainRows].filter(Boolean).join('\n'))
    .replace(canonicalSeparator, selectedSeparator);
  writeFileSync(join(teamDir, 'team.md'), nativeTeam(root, rows, separator));
  writeFileSync(join(teamDir, 'trace.jsonl'), '');
  for (const f of agentFiles) writeFileSync(join(root, '.codex', 'agents', `${f}.toml`), AGENT_BODY(f));
  return root;
}

/** A file that lives OUTSIDE the project root — the BCOP08 victim. */
function makeVictim(label, body) {
  const p = join(BASE, label, 'outside', 'README.md');
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, body);
  return p;
}

