#!/usr/bin/env node
/**
 * Suite B — parked/live collision on the project-global agent namespace
 * (scripts/toggle-team.sh enable, scripts/verify-team.sh).
 * Covers BC-V2-H01: `.claude/agents/<name>.md` is shared by the whole project, so a live file may
 * appear while a team is parked. `enable` used to `mv` the parked copy straight over it, and the
 * live-first if/parked-elif verifier read the resulting dual copy as HEALTHY.
 * Runs entirely inside an isolated temp base; never touches the real ~/.claude or the repo tree.
 * Assertion policy: unconditional exact-equality checks with a description.
 */
import { spawnSync } from 'node:child_process';
import {
  mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, rmSync, realpathSync, existsSync,
} from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const HERE = join(fileURLToPath(import.meta.url), '..');
const TOGGLE = join(HERE, '..', 'scripts', 'toggle-team.sh');
const VERIFY = join(HERE, '..', 'scripts', 'verify-team.sh');

// realpath: macOS /var is a symlink to /private/var
const BASE = realpathSync(mkdtempSync(join(tmpdir(), 'teams-conflict-')));
let passed = 0;
let failed = 0;
const results = [];

function deepEqual(a, b) {
  if (a === b) return true;
  if (typeof a !== typeof b) return false;
  if (a === null || b === null) return false;
  if (typeof a !== 'object') return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const ak = Object.keys(a);
  const bk = Object.keys(b);
  if (ak.length !== bk.length) return false;
  for (const k of ak) {
    if (!Object.prototype.hasOwnProperty.call(b, k)) return false;
    if (!deepEqual(a[k], b[k])) return false;
  }
  return true;
}

/** JSON, capped: a failed byte comparison must not bury the report under a whole agent file. */
function render(v) {
  const s = JSON.stringify(v);
  return s.length <= 220 ? s : `${s.slice(0, 220)}...<${s.length} chars>`;
}

function check(name, actual, expected, message) {
  if (deepEqual(actual, expected)) {
    passed++;
    results.push(`  PASS  ${name}  (${message})`);
  } else {
    failed++;
    results.push(`  FAIL  ${name}  (${message} | actual=${render(actual)} expected=${render(expected)})`);
  }
}

function run(script, args, cwd) {
  const r = spawnSync('bash', [script, ...args], { cwd, encoding: 'utf8', timeout: 20000 });
  return { stdout: r.stdout || '', stderr: r.stderr || '', status: r.status };
}

/**
 * Trailing `KEY:VALUE` summary block of toggle-team.sh, as an object. Read from the LAST occurrence
 * of each key: per-file progress lines share the `MOVED:`/`CONFLICT:` prefix with the summary.
 */
function summary(stdout) {
  const out = {};
  for (const key of ['ACTION', 'TEAM', 'MOVED', 'SKIPPED', 'MISSING', 'INVALID', 'CONFLICT']) {
    const hits = [...stdout.matchAll(new RegExp(`^${key}:(.*)$`, 'gm'))];
    out[key] = hits.length === 0 ? '<absent>' : hits[hits.length - 1][1];
  }
  return out;
}

const has = (stdout, needle) => stdout.split('\n').some((l) => l.includes(needle));

/** Trailing `KEY:VALUE` counter block of verify-team.sh. Same shape as toggle's summary. */
function verifyCounts(stdout) {
  const out = {};
  for (const key of ['DISABLED_AGENTS', 'CONFLICT_AGENTS']) {
    const hits = [...stdout.matchAll(new RegExp(`^${key}:(.*)$`, 'gm'))];
    out[key] = hits.length === 0 ? '<absent>' : hits[hits.length - 1][1];
  }
  return out;
}

const AGENT_BODY = (name) => `---\nname: ${name}\ndescription: fixture agent\n---\n\n# ${name}\n`;
const FOREIGN_BODY = '---\nname: worker-one\ndescription: written by SOMEONE ELSE\n---\n\n# hands off\n';
const SEP = '|-------|--------|---------|--------|---------|------|---------|';

/** A project root with one team whose roster is `rows`; every row also gets a live agent file. */
function makeProject(label, rows) {
  const root = join(BASE, label, 'proj');
  const teamDir = join(root, '.claude', 'teams', 't1');
  mkdirSync(join(root, '.claude', 'agents'), { recursive: true });
  mkdirSync(teamDir, { recursive: true });
  writeFileSync(
    join(teamDir, 'team.md'),
    [
      '# Team: t1',
      '',
      '| Field | Value |',
      '|-------|-------|',
      '| Created | 2026-08-16 |',
      '| Version | 6.0.0 |',
      '| Content version | 6.0.0 |',
      '| Generated by | brewcode:teams-setup |',
      '| Last update | 2026-08-16 |',
      `| Agents | ${rows.filter((name) => name !== 'intent-guard').length} |`,
      `| Project | ${root} |`,
      '',
      '## Agents',
      '',
      '| Agent | Domain | Mission | Status | Updated | Kind | Version |',
      SEP,
      ...rows.map((a) => `| ${a} | api | fixture mission | active | 2026-08-16 | domain | 6.0.0 |`),
      '',
    ].join('\n'),
  );
  writeFileSync(join(teamDir, 'trace.jsonl'), '');
  for (const a of rows) writeFileSync(join(root, '.claude', 'agents', `${a}.md`), AGENT_BODY(a));
  return root;
}

const ls = (dir) => readdirSync(dir).sort();
const readOrGone = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : '<file gone>');

/** Park the team, then let a third party write a live `worker-one.md` into the shared namespace. */
function makeCollision(label) {
  const root = makeProject(label, ['worker-one', 'worker-two', 'intent-guard']);
  const off = run(TOGGLE, ['t1', 'disable'], root);
  const live = join(root, '.claude', 'agents', 'worker-one.md');
  writeFileSync(live, FOREIGN_BODY);
  return { root, off, live, parked: `${live}.disabled` };
}

// ────────────────────────────────────────────────────────────────────────────
// B1 — BC-V2-H01: enable must refuse a live/parked collision and move NOTHING.
// ────────────────────────────────────────────────────────────────────────────
{
  const { root, off, live, parked } = makeCollision('b1');
  check('b1.disableStatus', off.status, 0, 'the fixture starts from a clean parked team');

  const r = run(TOGGLE, ['t1', 'enable'], root);
  check('b1.status', r.status, 1, 'enable exits non-zero when live and parked both exist');
  check(
    'b1.summary',
    summary(r.stdout),
    {
      ACTION: 'enable', TEAM: 't1', MOVED: '0', SKIPPED: '0', MISSING: '0', INVALID: '0', CONFLICT: '1',
    },
    'the refusal is all-or-nothing: one conflict, zero moves',
  );
  check(
    'b1.conflictLine',
    r.stdout.split('\n').filter((l) => l.startsWith('CONFLICT:worker-one')),
    [`CONFLICT:worker-one -- both .claude/agents/worker-one.md and .claude/agents/worker-one.md.disabled exist; enable would overwrite the live file. Nothing was touched.`],
    'the refusal names the agent and both conflicting paths',
  );
  check('b1.liveBytes', readOrGone(live), FOREIGN_BODY, 'the foreign live file is byte-preserved');
  check('b1.parkedBytes', readOrGone(parked), AGENT_BODY('worker-one'), 'the parked file is byte-preserved');
  check(
    'b1.agentsDir',
    ls(join(root, '.claude', 'agents')),
    ['intent-guard.md', 'worker-one.md', 'worker-one.md.disabled', 'worker-two.md.disabled'],
    'no member was unparked: a collision on ANY row aborts before the first mv',
  );
  check('b1.noVerdict', has(r.stdout, '✅ enable'), false, 'no success verdict is printed');
}

// ────────────────────────────────────────────────────────────────────────────
// B2 — the dry run refuses the same collision instead of printing a WOULD plan.
// ────────────────────────────────────────────────────────────────────────────
{
  const { root, live, parked } = makeCollision('b2');
  const r = run(TOGGLE, ['t1', 'enable', '--dry-run'], root);
  check('b2.status', r.status, 1, 'a dry run reports the collision as a failure too');
  check('b2.wouldLines', r.stdout.split('\n').filter((l) => l.startsWith('WOULD:')), [], 'no move is planned');
  check('b2.liveBytes', readOrGone(live), FOREIGN_BODY, 'the dry run left the live file byte-identical');
  check('b2.parkedBytes', readOrGone(parked), AGENT_BODY('worker-one'), 'the dry run left the parked file byte-identical');
}

// ────────────────────────────────────────────────────────────────────────────
// B3 — verify must report the dual copy as CONFLICT and FAIL, not as healthy.
// ────────────────────────────────────────────────────────────────────────────
{
  const { root } = makeCollision('b3');
  const r = run(VERIFY, ['t1'], root);
  check('b3.status', r.status, 1, 'verify exits 1 on a dual-copy agent');
  check('b3.checkLine', has(r.stdout, 'CHECK: agent worker-one ... CONFLICT'), true, 'the agent row reads CONFLICT');
  check(
    'b3.conflictDetail',
    has(r.stdout, 'CONFLICT: both .claude/agents/worker-one.md and .claude/agents/worker-one.md.disabled exist.'),
    true,
    'the detail line names both paths',
  );
  check('b3.verdict', has(r.stdout, 'VERIFY: FAIL'), true, 'the overall verdict is FAIL');
  check('b3.notPass', r.stdout.split('\n').filter((l) => l.startsWith('VERIFY: PASS')), [], 'no PASS verdict is printed');
  // D4: the counters must agree with the CONFLICT line above them. worker-one is conflicted (not
  // disabled), worker-two is the only parked-only member, intent-guard is live.
  check(
    'b3.counts',
    verifyCounts(r.stdout),
    { DISABLED_AGENTS: '1', CONFLICT_AGENTS: '1' },
    'the conflicted member is counted as CONFLICT, never folded into DISABLED',
  );
}

// ────────────────────────────────────────────────────────────────────────────
// B4 — regression: a clean park/unpack round trip still works end to end.
// ────────────────────────────────────────────────────────────────────────────
{
  const root = makeProject('b4', ['worker-one', 'worker-two', 'intent-guard']);
  const off = run(TOGGLE, ['t1', 'disable'], root);
  const on = run(TOGGLE, ['t1', 'enable'], root);
  check('b4.disableStatus', off.status, 0, 'disable succeeds');
  check('b4.enableStatus', on.status, 0, 'enable succeeds when no live file blocks it');
  check(
    'b4.enableSummary',
    summary(on.stdout),
    {
      ACTION: 'enable', TEAM: 't1', MOVED: '2', SKIPPED: '1', MISSING: '0', INVALID: '0', CONFLICT: '0',
    },
    'both members unparked, intent-guard skipped, no conflict',
  );
  check(
    'b4.agentsDir',
    ls(join(root, '.claude', 'agents')),
    ['intent-guard.md', 'worker-one.md', 'worker-two.md'],
    'every member is live again and no .md.disabled is left behind',
  );
  check('b4.bytes', readOrGone(join(root, '.claude', 'agents', 'worker-one.md')), AGENT_BODY('worker-one'), 'the round trip preserved every byte');
  const v = run(VERIFY, ['t1'], root);
  check('b4.verify', v.status, 0, 'verify passes on the restored team');
  check(
    'b4.verifyCounts',
    verifyCounts(v.stdout),
    { DISABLED_AGENTS: '0', CONFLICT_AGENTS: '0' },
    'a healthy team reports zero parked and zero conflicted members',
  );
}

// ────────────────────────────────────────────────────────────────────────────
// B5 — BC-V2-H01, opposite direction: disable must refuse the same collision.
// `mv live -> parked` destroys the parked body exactly as `mv parked -> live`
// destroys the live one; the refusal is symmetric and all-or-nothing.
// ────────────────────────────────────────────────────────────────────────────
{
  const { root, live, parked } = makeCollision('b5');
  const r = run(TOGGLE, ['t1', 'disable'], root);
  check('b5.status', r.status, 1, 'disable exits non-zero when live and parked both exist');
  check(
    'b5.summary',
    summary(r.stdout),
    {
      ACTION: 'disable', TEAM: 't1', MOVED: '0', SKIPPED: '0', MISSING: '0', INVALID: '0', CONFLICT: '1',
    },
    'the refusal is all-or-nothing: one conflict, zero moves',
  );
  check(
    'b5.conflictLine',
    r.stdout.split('\n').filter((l) => l.startsWith('CONFLICT:worker-one')),
    ['CONFLICT:worker-one -- both .claude/agents/worker-one.md and .claude/agents/worker-one.md.disabled exist; disable would overwrite the parked file. Nothing was touched.'],
    'the refusal names the agent, both paths and the parked victim',
  );
  check('b5.liveBytes', readOrGone(live), FOREIGN_BODY, 'the live file is byte-preserved');
  check('b5.parkedBytes', readOrGone(parked), AGENT_BODY('worker-one'), 'the parked file is byte-preserved');
  check(
    'b5.agentsDir',
    ls(join(root, '.claude', 'agents')),
    ['intent-guard.md', 'worker-one.md', 'worker-one.md.disabled', 'worker-two.md.disabled'],
    'nothing moved: a collision on ANY row aborts before the first mv',
  );
  check('b5.noVerdict', has(r.stdout, '✅ disable'), false, 'no success verdict is printed');
}

// ────────────────────────────────────────────────────────────────────────────
// B6 — the disable dry run refuses too, instead of printing a WOULD plan.
// ────────────────────────────────────────────────────────────────────────────
{
  const { root, live, parked } = makeCollision('b6');
  const r = run(TOGGLE, ['t1', 'disable', '--dry-run'], root);
  check('b6.status', r.status, 1, 'a dry run reports the collision as a failure too');
  check('b6.wouldLines', r.stdout.split('\n').filter((l) => l.startsWith('WOULD:')), [], 'no move is planned');
  check('b6.liveBytes', readOrGone(live), FOREIGN_BODY, 'the dry run left the live file byte-identical');
  check('b6.parkedBytes', readOrGone(parked), AGENT_BODY('worker-one'), 'the dry run left the parked file byte-identical');
}

// ────────────────────────────────────────────────────────────────────────────
// B7 — regression: the ordinary single-copy disable path is untouched.
// ────────────────────────────────────────────────────────────────────────────
{
  const root = makeProject('b7', ['worker-one', 'worker-two', 'intent-guard']);
  const r = run(TOGGLE, ['t1', 'disable'], root);
  check('b7.status', r.status, 0, 'disable succeeds when no parked file blocks it');
  check(
    'b7.summary',
    summary(r.stdout),
    {
      ACTION: 'disable', TEAM: 't1', MOVED: '2', SKIPPED: '1', MISSING: '0', INVALID: '0', CONFLICT: '0',
    },
    'both members parked, intent-guard skipped, no conflict',
  );
  check(
    'b7.agentsDir',
    ls(join(root, '.claude', 'agents')),
    ['intent-guard.md', 'worker-one.md.disabled', 'worker-two.md.disabled'],
    'every member is parked and no live .md is left behind',
  );
  check('b7.bytes', readOrGone(join(root, '.claude', 'agents', 'worker-one.md.disabled')), AGENT_BODY('worker-one'), 'parking preserved every byte');
  check('b7.verdict', has(r.stdout, '✅ disable'), true, 'the success verdict is printed');
  const v = run(VERIFY, ['t1'], root);
  check('b7.verifyStatus', v.status, 0, 'verify passes on a cleanly parked team');
  check(
    'b7.verifyCounts',
    verifyCounts(v.stdout),
    { DISABLED_AGENTS: '2', CONFLICT_AGENTS: '0' },
    'an ordinary parked team counts both members as DISABLED and none as CONFLICT',
  );
}

// ── report ──────────────────────────────────────────────────────────────────
rmSync(BASE, { recursive: true, force: true });
console.log('suite-parked-conflict.mjs');
for (const line of results) console.log(line);
console.log(`  ${passed} passed, ${failed} failed`);
process.exit(failed === 0 ? 0 : 1);
