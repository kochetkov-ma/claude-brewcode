#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';

const STATUS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BREWCODE = resolve(STATUS_DIR, '../..');
const source = ['SKILL.md', 'references/phase1-probes.md', 'references/phase2-stamps.md', 'references/task-tools-offer.md']
  .map(f => readFileSync(join(STATUS_DIR, f), 'utf8')).join('\n');
const stamps = [...source.matchAll(/```bash\n([\s\S]*?)\n```/g)].map(match => match[1])
  .find(block => block.includes("<<'STAMPS'"));
const producer = readFileSync(join(BREWCODE, 'skills/teams-setup/SKILL.md'), 'utf8');
const contentVersion = producer.match(/brewcode-meta:.*?content_version=([^\s>]+)/)[1];
const headerRows = producer.match(/\| Version \| \{PLUGIN_VERSION\} \|\n\s*\| Content version \| \{CONTENT_VERSION\} \|\n\s*\| Generated by \| brewcode:teams-setup \|\n\s*\| Last update \| \{LAST_UPDATED\} \|/)[0]
  .split('\n').map(line => line.trim()).join('\n');

function readStamps(root, command = stamps) {
  // Paths reach bash via env, never spliced into the command text.
  const script = command.replace('PLUGIN_ROOT=/abs/root/printed/by/phase0', 'PLUGIN_ROOT="${SUBST_PLUGIN_ROOT}"')
    .replaceAll('${CLAUDE_SKILL_DIR}', '${SUBST_SKILL_DIR}');
  const result = spawnSync('bash', ['-e', '-o', 'pipefail', '-c', script], {
    cwd: root, encoding: 'utf8', env: { ...process.env, HOME: root, CLAUDE_CONFIG_DIR: join(root, 'cfg'), CLAUDE_PROJECT_DIR: root,
      SUBST_PLUGIN_ROOT: BREWCODE, SUBST_SKILL_DIR: STATUS_DIR }, timeout: 10000,
  });
  assert.equal(result.status, 0, `actual shipped stamp probe must succeed: ${result.stderr}`);
  return result.stdout;
}

test('team.md content version written by teams-setup is read against the producer source', t => {
  // GIVEN: a team.md carrying the producer's exact header rows, written by an older plugin release.
  const root = mkdtempSync(join(tmpdir(), 'team-md-cv-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const team = join(root, '.claude/teams/demo/team.md');
  mkdirSync(dirname(team), { recursive: true });
  writeFileSync(team, `# Team demo\n\n| Field | Value |\n|-------|-------|\n${headerRows
    .replace('{PLUGIN_VERSION}', '0.0.1').replace('{CONTENT_VERSION}', contentVersion)
    .replace('{LAST_UPDATED}', '2026-10-12')}\n`);
  // WHEN: the actual Phase 2a probe reads the brewcode carriers.
  const versions = readStamps(root);
  // THEN: the lowercase-v producer row is the comparison value, not the stale plugin version.
  assert.equal(versions.includes(`CURRENT   .claude/teams/demo/team.md (${contentVersion}, cv-src)`), true,
    `team.md must compare its Content version row against the teams-setup source:\n${versions}`);
});
