#!/usr/bin/env node
/**
 * Suite A — teams lifecycle roster safety (scripts/toggle-team.sh, scripts/verify-team.sh).
 * Covers BCOP08: a `## Agents` roster value is interpolated into move/probe/delete paths, so a row
 * like `../../../outside/README` renamed a file OUTSIDE the project. Runs entirely inside an isolated
 * temp base; never touches the real ~/.codex or the repo tree.
 * Assertion policy: unconditional exact-equality checks with a description.
 */
import { spawnSync } from 'node:child_process';
import {
  mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, rmSync, realpathSync, existsSync,
} from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const HERE = join(fileURLToPath(import.meta.url), '..');
const TOGGLE = join(HERE, '..', 'scripts', 'toggle-team.sh');
const VERIFY = join(HERE, '..', 'scripts', 'verify-team.sh');

// realpath: macOS /var is a symlink to /private/var
const BASE = realpathSync(mkdtempSync(join(tmpdir(), 'teams-lifecycle-')));
let passed = 0;
let failed = 0;
const results = [];

function deepEqual(a, b) {
  if (a === b) return true;
  if (typeof a !== typeof b) return false;
  if (a === null || b === null) return false;
  if (typeof a !== 'object') return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const ak = Object.keys(a);
  const bk = Object.keys(b);
  if (ak.length !== bk.length) return false;
  for (const k of ak) {
    if (!Object.prototype.hasOwnProperty.call(b, k)) return false;
    if (!deepEqual(a[k], b[k])) return false;
  }
  return true;
}

/** JSON, capped: a failed byte comparison must not bury the report under a whole agent file. */
function render(v) {
  const s = JSON.stringify(v);
  return s.length <= 220 ? s : `${s.slice(0, 220)}...<${s.length} chars>`;
}

function check(name, actual, expected, message) {
  if (deepEqual(actual, expected)) {
    passed++;
    results.push(`  PASS  ${name}  (${message})`);
  } else {
    failed++;
    results.push(`  FAIL  ${name}  (${message} | actual=${render(actual)} expected=${render(expected)})`);
  }
}

function run(script, args, cwd) {
  const r = spawnSync('bash', [script, ...args], { cwd, encoding: 'utf8', timeout: 20000 });
  return { stdout: r.stdout || '', stderr: r.stderr || '', status: r.status };
}

/**
 * Trailing `KEY:VALUE` summary block of toggle-team.sh, as an object. Read from the LAST occurrence
 * of each key: per-file progress lines share the `MOVED:` prefix with the summary.
 */
function summary(stdout) {
  const out = {};
  for (const key of ['ACTION', 'TEAM', 'MOVED', 'SKIPPED', 'MISSING', 'INVALID']) {
    const hits = [...stdout.matchAll(new RegExp(`^${key}:(.*)$`, 'gm'))];
    out[key] = hits.length === 0 ? '<absent>' : hits[hits.length - 1][1];
  }
  return out;
}

const linesStartingWith = (stdout, prefix) =>
  stdout.split('\n').filter((l) => l.startsWith(prefix));

const DOMAIN_INSTRUCTIONS = '## Mission\nOwn fixture behavior.\n\n## Owned surfaces\nFixture files.\n\n## Exclusions\nNo neighboring work.\n\n## Must-load references\n- `.codex/teams/t1/team.md`\n\n## Unique invariants\nPreserve bytes.\n\n## Unique verification\nRun the fixture suite.\n';
const AGENT_BODY = (name) => name === 'intent-guard'
  ? `name = "intent-guard"\ndescription = "Review-only fixture."\ndeveloper_instructions = "Review-only. Never implement and never mutate project files. Report a verdict with file:line evidence."\n`
  : `name = ${JSON.stringify(name)}\ndescription = "Domain fixture agent."\ndeveloper_instructions = ${JSON.stringify(DOMAIN_INSTRUCTIONS)}\n`;

/**
 * The `## Agents` header separator, in the three spellings the parser must tell apart: the compact
 * one the shipped template writes, the space-padded one a markdown formatter produces, and none.
 */
const SEPARATORS = {
  compact: '|-------|--------|---------|--------|---------|------|---------|',
  padded: '| ------- | -------- | --------- | -------- | --------- | ------ | --------- |',
  none: null,
};

/**
 * A project root with one team. `rows` are `## Agents` Agent-column values, in table order;
 * `agentFiles` are the names actually written to .codex/agents/.
 */
const NATIVE_TEAM_TEMPLATE = "# Team: {TEAM_NAME}\n|Field|Value|\n|---|---|\n|Created|{DATE}|\n|Version|{PLUGIN_VERSION}|\n|Content version|{CONTENT_VERSION}|\n|Generated by|brewcode:teams-setup|\n|Last update|{LAST_UPDATED}|\n|Agents|{N}|\n|Intent guard|{INTENT_GUARD_POLICY}|\n|Project|{CWD}|\n\n## Shared Agent Contract\nEvery domain agent loads this file before task acceptance. `intent-guard` is exempt: it keeps its review-only output contract and never implements.\nBefore any task evaluate `Domain`, `Duplicate`, `Best candidate`. Mismatch/duplicate/better -> refuse+owner/link+return; accept -> trace `took`, execute only owned surfaces; profile exclusions win on overlap.\nOptional best effort, `1 attempt max`, no retry, Bash only. Use versionless project-local `.codex/teams/{TEAM_NAME}/trace-ops.sh`; project agents get !=`<plugin-root>` substitution and no `*_PLUGIN_ROOT` env. Missing/fail -> skip; plugin update/move/uninstall does not break it.\n`T=\".codex/teams/{TEAM_NAME}\"; bash \"$T/trace-ops.sh\" add \"$T\" \"$SID\" \"{AGENT_NAME}\" \"<kind>\" \"<state>\" \"<text>\"`\nTrack states: `took` / `refused` / `completed` / `failed`. Issue severity: `low` / `medium` / `high` / `critical`. Insight category (max 1-3): `pattern` / `architecture` / `performance` / `security` / `convention` / `debt`. `$SID` is 8 chars; else any 8-char marker.\nA task traced `took` ends with exactly one terminal track: `completed` or `failed`.\nVerdict first, <=30 lines, `path:line`. !=bodies/output/log/preamble. This holds with or without agent-return. Return changed path/check only. Bulk -> `.codex/reports/YYYYMMDD-HHMMSS_{AGENT_NAME}/`; return path, !=content. With agent-return: >~1000 est-tokens (`chars/4`) -> compress; >~2500 -> file detail, path + verdict + <=3 lines.\nActual scale; !=imagined load/speculative abstraction (EX: 10-user app !=lock-contention hardening). Simplify. Class/module/test -> nearest repo etalon (`.codex/convention/*` first), additive to rules/conventions/docs, !=replace them.\n\n## Agents\n|Agent|Domain|Mission|Status|Updated|Kind|Version|\n|---|---|---|---|---|---|---|\n{INTENT_GUARD_ROW}";
function nativeTeam(root, rows, separator = 'compact') {
  const intent = rows.includes('intent-guard');
  const domainRows = rows.filter((name) => name !== 'intent-guard');
  const intentRow = intent ? '|intent-guard|--|Anti-drift check: what was ASKED vs what was DELIVERED|active|2026-08-27|review-only|6.1.4|' : '';
  const roster = rows.map((name) => name === 'intent-guard' ? intentRow : `|${name}|api|fixture mission|active|2026-08-27|domain|6.1.4|`).join('\n');
  const rendered = `${NATIVE_TEAM_TEMPLATE
    .replaceAll('{TEAM_NAME}', 't1')
    .replaceAll('{DATE}', '2026-08-27')
    .replaceAll('{LAST_UPDATED}', '2026-08-27')
    .replaceAll('{PLUGIN_VERSION}', '6.1.4')
    .replaceAll('{CONTENT_VERSION}', '6.1.0')
    .replaceAll('{N}', String(domainRows.length))
    .replaceAll('{CWD}', root)
    .replaceAll('{INTENT_GUARD_POLICY}', intent ? 'required' : 'legacy-absent')
    .replaceAll('{INTENT_GUARD_ROW}', roster)}\n`;
  const separators = { compact: '|---|---|---|---|---|---|---|', padded: '| --- | --- | --- | --- | --- | --- | --- |', none: '' };
  return rendered.replace('|---|---|---|---|---|---|---|', separators[separator]);
}

function makeProject(label, rows, agentFiles, separator = 'compact') {
  const root = join(BASE, label, 'proj');
  const teamDir = join(root, '.codex', 'teams', 't1');
  mkdirSync(join(root, '.codex', 'agents'), { recursive: true });
  mkdirSync(teamDir, { recursive: true });
  const rosterRows = rows
    .map((a) => `| ${a} | api | fixture mission | active | 2026-08-16 | domain | 6.0.0 |`)
    .join('\n');
  writeFileSync(join(teamDir, 'team.md'), nativeTeam(root, rows, separator));
  writeFileSync(join(teamDir, 'trace.jsonl'), '');
  for (const f of agentFiles) writeFileSync(join(root, '.codex', 'agents', `${f}.toml`), AGENT_BODY(f));
  return root;
}

/** A file that lives OUTSIDE the project root — the BCOP08 victim. */
function makeVictim(label, body) {
  const p = join(BASE, label, 'outside', 'README.md');
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, body);
  return p;
}

const ls = (dir) => readdirSync(dir).sort();
// A renamed victim is the BCOP08 failure itself, so reading it must report, never throw.
const readOrGone = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : '<file gone>');
const TRAVERSAL = '../../../outside/README';

// ────────────────────────────────────────────────────────────────────────────
// A1 — BCOP08: a traversal roster row must move nothing, inside or outside.
// ────────────────────────────────────────────────────────────────────────────
{
  const root = makeProject('a1', ['worker-one', TRAVERSAL, 'intent-guard'], ['worker-one', 'intent-guard']);
  const victim = makeVictim('a1', 'VICTIM\n');
  const r = run(TOGGLE, ['t1', 'disable'], root);

  check('a1.status', r.status, 1, 'disable exits 1 when a roster row is not an agent id');
  check(
    'a1.summary',
    summary(r.stdout),
    { ACTION: 'disable', TEAM: 't1', MOVED: '1', SKIPPED: '1', MISSING: '0', INVALID: '1' },
    'one valid member parked, intent-guard skipped, one row refused',
  );
  check(
    'a1.skipLines',
    linesStartingWith(r.stdout, 'SKIP:'),
    [
      `SKIP:invalid agent id '${TRAVERSAL}' (not ^[a-z0-9][a-z0-9-]*$) -- nothing under .codex/agents touched`,
      'SKIP:intent-guard (shared with superreview-setup)',
    ],
    'the refusal names the offending value and precedes the intent-guard skip',
  );
  check('a1.victimBytes', readOrGone(victim), 'VICTIM\n', 'the file outside the project is byte-unchanged');
  check(
    'a1.outsideDir',
    ls(join(BASE, 'a1', 'outside')),
    ['README.md'],
    'no .md.disabled was created outside the project',
  );
  check(
    'a1.agentsDir',
    ls(join(root, '.codex', 'agents')),
    ['intent-guard.toml', 'worker-one.toml.disabled'],
    'only the valid member was parked; intent-guard stayed live',
  );
}

// ────────────────────────────────────────────────────────────────────────────
// A2 — the dry run refuses the same row: `WOULD:` never names a path outside.
// ────────────────────────────────────────────────────────────────────────────
{
  const root = makeProject('a2', ['worker-one', TRAVERSAL], ['worker-one']);
  const victim = makeVictim('a2', 'VICTIM\n');
  const r = run(TOGGLE, ['t1', 'disable', '--dry-run'], root);

  check('a2.status', r.status, 1, 'the dry run reports the invalid row as a failure too');
  check(
    'a2.wouldLines',
    linesStartingWith(r.stdout, 'WOULD:'),
    ['WOULD:.codex/agents/worker-one.toml -> .codex/agents/worker-one.toml.disabled'],
    'exactly one planned move, and it is inside .codex/agents/',
  );
  check('a2.victimBytes', readOrGone(victim), 'VICTIM\n', 'dry run leaves the outside file alone');
  check(
    'a2.agentsDir',
    ls(join(root, '.codex', 'agents')),
    ['worker-one.toml'],
    'dry run writes nothing',
  );
}

// ────────────────────────────────────────────────────────────────────────────
// A3 — the full rejected shape set: traversal, slash, leading dot, uppercase,
//      underscore. An empty Agent cell is skipped silently, as before.
